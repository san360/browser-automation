#!/bin/sh
# Post-provision hook (Linux / macOS). Mirrors hooks/postprovision.ps1:
#  1. Creates (or reuses) the Foundry Toolbox exposing the GA Browser Automation tool.
#  2. Writes a local .env file with non-secret endpoints for the demo CLI.
set -eu

get_env() { azd env get-value "$1" 2>/dev/null || true; }

PROJECT_ENDPOINT="$(get_env FOUNDRY_PROJECT_ENDPOINT)"
CONNECTION_ID="$(get_env BROWSER_AUTOMATION_PROJECT_CONNECTION_ID)"
TOOLBOX_NAME="$(get_env TOOLBOX_NAME)"
TOOLBOX_NAME="${TOOLBOX_NAME:-browser-automation-tools}"
PREVIOUS_CONNECTION="$(get_env TOOLBOX_CONNECTION_ID)"

if [ -z "$PROJECT_ENDPOINT" ] || [ -z "$CONNECTION_ID" ]; then
  echo "FOUNDRY_PROJECT_ENDPOINT or BROWSER_AUTOMATION_PROJECT_CONNECTION_ID is missing." >&2
  exit 1
fi

echo ""
echo "== Browser Automation toolbox =="
# Use azd's identity (works even when the Azure CLI is signed in to a different tenant).
TOKEN="$(azd auth token --scope https://ai.azure.com/.default --output json | sed -n 's/.*"token"[[:space:]]*:[[:space:]]*"\([^"]*\)".*/\1/p')"

EXISTS="$(curl -s -o /dev/null -w '%{http_code}' -H "Authorization: Bearer $TOKEN" \
  "$PROJECT_ENDPOINT/toolboxes/$TOOLBOX_NAME?api-version=v1" || true)"

if [ "$EXISTS" = "200" ] && [ "$PREVIOUS_CONNECTION" = "$CONNECTION_ID" ]; then
  echo "Toolbox '$TOOLBOX_NAME' already published; skipping."
else
  BODY=$(printf '{"description":"GA Browser Automation tool backed by the demo Playwright workspace","tools":[{"type":"browser_automation","browser_automation":{"connection":{"project_connection_id":"%s"}}}]}' "$CONNECTION_ID")
  VERSION=""
  ATTEMPT=1
  while [ $ATTEMPT -le 5 ] && [ -z "$VERSION" ]; do
    RESPONSE="$(curl -s -X POST -H "Authorization: Bearer $TOKEN" -H 'Content-Type: application/json' \
      -d "$BODY" "$PROJECT_ENDPOINT/toolboxes/$TOOLBOX_NAME/versions?api-version=v1" || true)"
    VERSION="$(printf '%s' "$RESPONSE" | sed -n 's/.*"version"[[:space:]]*:[[:space:]]*"\([^"]*\)".*/\1/p')"
    if [ -z "$VERSION" ]; then
      echo "  attempt $ATTEMPT failed: $RESPONSE"
      ATTEMPT=$((ATTEMPT + 1))
      sleep 15
    fi
  done
  [ -n "$VERSION" ] || { echo "Could not create a toolbox version." >&2; exit 1; }
  azd ai toolbox publish "$TOOLBOX_NAME" "$VERSION" --project-endpoint "$PROJECT_ENDPOINT" --no-prompt
  azd env set TOOLBOX_NAME "$TOOLBOX_NAME" >/dev/null
  azd env set TOOLBOX_CONNECTION_ID "$CONNECTION_ID" >/dev/null
  echo "Toolbox '$TOOLBOX_NAME' version $VERSION created and published."
fi
azd env set TOOLBOX_ENDPOINT "$PROJECT_ENDPOINT/toolboxes/$TOOLBOX_NAME/mcp?api-version=v1" >/dev/null

echo ""
echo "== Local .env for the demo CLI =="
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
{
  echo "# Generated by hooks/postprovision.sh from the azd environment."
  azd env get-values | grep -E '^(AZURE_ENV_NAME|AZURE_SUBSCRIPTION_ID|AZURE_LOCATION|AZURE_FOUNDRY_RESOURCE_GROUP|AZURE_PLATFORM_RESOURCE_GROUP|AZURE_AI_ACCOUNT_NAME|AZURE_AI_PROJECT_NAME|AZURE_AI_PROJECT_ID|FOUNDRY_PROJECT_ENDPOINT|AZURE_OPENAI_ENDPOINT|BROWSER_AUTOMATION_CONNECTION_NAME|BROWSER_AUTOMATION_PROJECT_CONNECTION_ID|TOOLBOX_NAME|TOOLBOX_ENDPOINT|PLAYWRIGHT_WORKSPACE_ID|PLAYWRIGHT_WORKSPACE_NAME|PLAYWRIGHT_BROWSER_ENDPOINT|DEMO_SITE_URL|DEMO_SITE_HOST|APPLICATIONINSIGHTS_CONNECTION_STRING|AZURE_APPLICATION_INSIGHTS_NAME)='
} > "$ROOT/.env"
echo "Wrote $ROOT/.env"

echo ""
echo "== Ready =="
echo "Foundry project : $PROJECT_ENDPOINT"
echo "Demo site       : $(get_env DEMO_SITE_URL)  (deploy it with: azd deploy demo-site)"
echo "Toolbox         : $TOOLBOX_NAME"
echo "Next            : azd deploy   then   python -m demo_cli list"
