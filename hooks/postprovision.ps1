# Post-provision hook (Windows / pwsh).
#  1. Creates (or reuses) the Foundry Toolbox that exposes the GA Browser Automation tool to the hosted agent.
#  2. Writes a local .env file with non-secret endpoints for the demo CLI, console and Computer Use runner.
#  3. Prints a short summary with next steps.
$ErrorActionPreference = 'Stop'

function Get-AzdEnv {
    $values = @{}
    azd env get-values 2>$null | ForEach-Object {
        if ($_ -match '^([^=]+)="(.*)"$') { $values[$Matches[1]] = $Matches[2] }
    }
    return $values
}

$envValues = Get-AzdEnv
$projectEndpoint = $envValues['FOUNDRY_PROJECT_ENDPOINT']
$connectionId = $envValues['BROWSER_AUTOMATION_PROJECT_CONNECTION_ID']
$toolboxName = if ($envValues['TOOLBOX_NAME']) { $envValues['TOOLBOX_NAME'] } else { 'browser-automation-tools' }

if (-not $projectEndpoint -or -not $connectionId) {
    Write-Error "FOUNDRY_PROJECT_ENDPOINT or BROWSER_AUTOMATION_PROJECT_CONNECTION_ID is missing. Did both infra layers provision?"
    exit 1
}

Write-Host ""
Write-Host "== Browser Automation toolbox =="
# Use azd's identity (works even when the Azure CLI is signed in to a different tenant).
$token = (azd auth token --scope "https://ai.azure.com/.default" --output json | ConvertFrom-Json).token
$headers = @{ Authorization = "Bearer $token"; 'Content-Type' = 'application/json' }

$needsVersion = $true
try {
    $existing = Invoke-RestMethod -Method GET -Headers $headers -Uri "$projectEndpoint/toolboxes/${toolboxName}?api-version=v1"
    if ($envValues['TOOLBOX_CONNECTION_ID'] -eq $connectionId -and $existing.default_version) {
        Write-Host "Toolbox '$toolboxName' already published (default version $($existing.default_version)); skipping."
        $needsVersion = $false
    }
} catch {
    Write-Host "Toolbox '$toolboxName' not found yet; creating it."
}

if ($needsVersion) {
    $body = @{
        description = 'GA Browser Automation tool backed by the demo Playwright workspace'
        tools = @(
            @{
                type = 'browser_automation'
                browser_automation = @{ connection = @{ project_connection_id = $connectionId } }
            }
        )
    } | ConvertTo-Json -Depth 6 -Compress

    $version = $null
    for ($attempt = 1; $attempt -le 5 -and -not $version; $attempt++) {
        try {
            $created = Invoke-RestMethod -Method POST -Headers $headers -Body $body `
                -Uri "$projectEndpoint/toolboxes/$toolboxName/versions?api-version=v1"
            $version = $created.version
        } catch {
            Write-Host "  attempt $attempt failed: $($_.Exception.Message). Retrying in 15s (RBAC propagation)..."
            Start-Sleep -Seconds 15
        }
    }
    if (-not $version) { Write-Error "Could not create a toolbox version."; exit 1 }

    azd ai toolbox publish $toolboxName $version --project-endpoint $projectEndpoint --no-prompt
    if ($LASTEXITCODE -ne 0) { Write-Error "Failed to publish toolbox version $version."; exit 1 }

    azd env set TOOLBOX_NAME $toolboxName | Out-Null
    azd env set TOOLBOX_CONNECTION_ID $connectionId | Out-Null
    Write-Host "Toolbox '$toolboxName' version $version created and published."
}
azd env set TOOLBOX_ENDPOINT "$projectEndpoint/toolboxes/$toolboxName/mcp?api-version=v1" | Out-Null

Write-Host ""
Write-Host "== Local .env for the demo CLI =="
$envValues = Get-AzdEnv
$keys = @(
    'AZURE_ENV_NAME', 'AZURE_SUBSCRIPTION_ID', 'AZURE_LOCATION', 'AZURE_FOUNDRY_RESOURCE_GROUP', 'AZURE_PLATFORM_RESOURCE_GROUP',
    'AZURE_AI_ACCOUNT_NAME', 'AZURE_AI_PROJECT_NAME', 'AZURE_AI_PROJECT_ID', 'FOUNDRY_PROJECT_ENDPOINT', 'AZURE_OPENAI_ENDPOINT',
    'BROWSER_AUTOMATION_CONNECTION_NAME', 'BROWSER_AUTOMATION_PROJECT_CONNECTION_ID', 'TOOLBOX_NAME', 'TOOLBOX_ENDPOINT',
    'PLAYWRIGHT_WORKSPACE_ID', 'PLAYWRIGHT_WORKSPACE_NAME', 'PLAYWRIGHT_BROWSER_ENDPOINT',
    'DEMO_SITE_URL', 'DEMO_SITE_HOST', 'APPLICATIONINSIGHTS_CONNECTION_STRING', 'AZURE_APPLICATION_INSIGHTS_NAME'
)
$lines = @('# Generated by hooks/postprovision.ps1 from the azd environment. Safe to delete; regenerate with `azd hooks run postprovision`.')
foreach ($k in $keys) { if ($envValues.ContainsKey($k)) { $lines += "$k=`"$($envValues[$k])`"" } }
$root = Split-Path -Parent $PSScriptRoot
Set-Content -Path (Join-Path $root '.env') -Value $lines -Encoding utf8
Write-Host "Wrote $(Join-Path $root '.env')"

Write-Host ""
Write-Host "== Ready =="
Write-Host "Foundry project : $($envValues['FOUNDRY_PROJECT_ENDPOINT'])"
Write-Host "Demo site       : $($envValues['DEMO_SITE_URL'])  (deploy it with: azd deploy demo-site)"
Write-Host "Playwright      : $($envValues['PLAYWRIGHT_WORKSPACE_NAME'])"
Write-Host "Toolbox         : $toolboxName"
Write-Host "Next            : azd deploy   then   python -m demo_cli list"
